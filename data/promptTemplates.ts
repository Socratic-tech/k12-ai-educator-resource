export const promptTemplateMap = Object.fromEntries(
  promptTemplates.map((template) => [template.id, template]),
) as Record<PromptWorkflowId, PromptTemplate>;

export function isPromptWorkflowId(
  value: string,
): value is PromptWorkflowId {
  return value in promptTemplateMap;
}
